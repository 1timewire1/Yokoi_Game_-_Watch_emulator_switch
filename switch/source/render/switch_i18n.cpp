uint8_t g_cache_lang = 0xFF;

bool all_digits(const std::string& s) {
    if (s.empty()) return false;
    for (char c : s) if (!isdigit((unsigned char)c)) return false;
    return true;
}
bool starts(const std::string& s, const char* p) { return s.compare(0, strlen(p), p) == 0; }
bool ends(const std::string& s, const char* p) {
    const size_t n = strlen(p);
    return s.size() >= n && s.compare(s.size() - n, n, p) == 0;
}

std::string to_spanish(const std::string& s) {
    auto it = g_table.find(s);
    if (it != g_table.end()) return it->second;

    // "Maker  |  12 games" and the like: each side on its own.
    const size_t bar = s.find("  |  ");
    if (bar != std::string::npos) {
        return to_spanish(s.substr(0, bar)) + "  |  " + to_spanish(s.substr(bar + 5));
    }
    // The selected settings row shows its value as "< value >".
    if (s.size() > 4 && starts(s, "< ") && ends(s, " >")) return "< " + to_spanish(s.substr(2, s.size() - 4)) + " >";
    if (starts(s, "Custom: ")) return "Personalizado: " + s.substr(8);
    if (starts(s, "Saved to Slot ")) return "Guardado en la ranura " + s.substr(14);
    if (starts(s, "Slot ") && all_digits(s.substr(5))) return "Ranura " + s.substr(5);
    const char* yes_no = "?   A: Yes   B: No";
    if (ends(s, yes_no)) {
        const std::string head = s.substr(0, s.size() - strlen(yes_no));
        if (starts(head, "Overwrite Slot ")) return "¿Sobrescribir la ranura " + head.substr(15) + "?   A: Sí   B: No";
        if (starts(head, "Delete Slot ")) return "¿Borrar la ranura " + head.substr(12) + "?   A: Sí   B: No";
    }
    if (starts(s, "This save is ") && ends(s, " old")) {
        std::string mid = s.substr(13, s.size() - 13 - 4);  // "30 hours" / "3 days"
        if (ends(mid, " hours")) mid = mid.substr(0, mid.size() - 6) + " horas";
        else if (ends(mid, " days")) mid = mid.substr(0, mid.size() - 5) + " días";
        return "Esta partida tiene " + mid;
    }
    if (ends(s, " games") && all_digits(s.substr(0, s.size() - 6))) return s.substr(0, s.size() - 6) + " juegos";
    if (ends(s, " game") && all_digits(s.substr(0, s.size() - 5))) return s.substr(0, s.size() - 5) + " juego";
    if (starts(s, "Sort by: ")) return "Ordenar por: " + to_spanish(s.substr(9));
    if (starts(s, ">> ") && ends(s, " left")) return ">> quedan " + s.substr(3, s.size() - 8);
    if (starts(s, "(") && ends(s, " beyond the cap skipped)")) {
        return "(" + s.substr(1, s.size() - 1 - 24) + " por encima del límite, omitidas)";
    }
    {   // pet catch-up "1h 02m of 3h 00m"
        const size_t of = s.find(" of ");
        if (of != std::string::npos && of > 0 && isdigit((unsigned char)s[0])) return s.substr(0, of) + " de " + s.substr(of + 4);
    }
    return s;
}


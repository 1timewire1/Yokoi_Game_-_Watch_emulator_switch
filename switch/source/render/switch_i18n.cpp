const char* switch_language_name(uint8_t lang) { return lang == kLangSpanish ? "Español" : "English"; }

const std::string& switch_tr(const std::string& en) {
    if (g_language != kLangSpanish) return en;
    if (g_table.empty()) {
        for (const auto& e : kEs) g_table.emplace(e[0], e[1]);
    }
    if (g_cache_lang != g_language) {
        g_cache.clear();
        g_cache_lang = g_language;
    }
    auto it = g_cache.find(en);
    if (it != g_cache.end()) return it->second;
    // Unbounded growth isn't a worry: it only ever holds what the menu
    // draws (its own texts plus game/maker names), a few hundred entries.
    return g_cache.emplace(en, to_spanish(en)).first->second;
}

const char* switch_tr_c(const char* en) {
    if (!en || g_language != kLangSpanish) return en;
    return switch_tr(std::string(en)).c_str();
}

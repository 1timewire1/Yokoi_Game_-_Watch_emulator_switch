namespace {
// Real-time thresholds (see LCDonald_fake_cpu.h's class comment for why
// these are wall-clock, not a synthetic per-call accumulator). Both come
// straight from the original C# (LCDLogicProcessor.cs): the base Update()
// timer is `new Timer(100)` in StartGame(), and GameLoop() polls input
// with `Thread.Sleep(10)` between passes.
constexpr uint64_t kTickUs = 100'000;
constexpr uint64_t kInputPollUs = 10'000;
}  // namespace

LCDonald_fake_cpu::LCDonald_fake_cpu() : SM5XX("LCDonald\0") {}

void LCDonald_fake_cpu::init() {
    // Called BEFORE load_rom() (see switch_game_loader.cpp) - program_ isn't
    // constructed yet, so this only resets state that doesn't depend on it,
    // matching David_And_John_fake_cpu::init()'s same ordering constraint.
    is_sleep = false;
    // SM5XX::cycle_curr_opcode has no default member initializer (see
    // SM5XX.h) - David_And_John_fake_cpu::init() explicitly zeroes it for
    // exactly this reason and this class missed doing the same. step()
    // only calls execute_curr_opcode() once cycle_curr_opcode counts down
    // to <=0 (see SM5XX::step()/execute_cycle()); left at whatever
    // indeterminate value happened to be on the stack/heap at construction,
    // a large positive garbage value means potentially billions of step()
    // calls before the game's logic ever runs once - in practice "hangs
    // with no segments," and inconsistently so, since that garbage value
    // depends on process memory layout and differs run to run, matching
    // exactly what showed up in testing even after the (separate, also
    // real) std::random_device fix.
    cycle_curr_opcode = 0;
    // 0 = "not started yet" - execute_curr_opcode() seeds both from the
    // real clock on its first call rather than firing tick()/custom_update()
    // immediately on a stale/zero timestamp.
    last_tick_time_us_ = 0;
    last_custom_update_time_us_ = 0;
    last_input_poll_time_us_ = 0;
    buffered_inputs_.clear();
    pending_inputs_.clear();
    endless_ = false;
    endless_score_ = 0;
}


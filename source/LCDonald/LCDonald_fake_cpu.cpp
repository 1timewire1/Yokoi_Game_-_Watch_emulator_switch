void LCDonald_fake_cpu::load_rom(const uint8_t* file_hex, size_t size_hex) {
    if (file_hex && size_hex > 0) {
        game_id_ = file_hex[size_hex - 1];
        select_game(game_id_);
    }
    // Deliberately NOT started here: a freshly loaded game sits on the
    // all-segments-lit "stopped" screen (LCDonald_program::is_stopped_ is
    // true until start() runs) - the Switch input layer then starts it as
    // Normal (+) or Endless (-) via start_game(), mimicking a Game & Watch's
    // Game A / Game B selection. The all-lit screen is also where a finished
    // run lands, so the same two buttons double as "play again".
    if (program_) {
        refresh_visible_cache();
    }
}

void LCDonald_fake_cpu::refresh_visible_cache() {
    if (!program_) return;
    visible_cache_ = program_->get_visible_game_elements();
}

void LCDonald_fake_cpu::execute_curr_opcode() {
    if (!program_) return;  // Out-of-range game id in load_rom() - shouldn't happen for the 20 valid ids.
    // update_segments_from_cpu() (switch_segments_state.cpp) only re-reads
    // get_segments_state() when this is true, then clears it itself - every
    // real CPU sets it once per executed opcode (see e.g. SM5XX_instruction.cpp),
    // and David_And_John_fake_cpu::execute_curr_opcode() does the same for
    // the other no-real-ROM engine. Without it the renderer keeps showing
    // frame 0's (all-off) segment snapshot forever, even though program_
    // itself is ticking normally underneath - segments never light up and
    // input appears to do nothing despite the game logic actually running.
    segments_state_are_update = true;

    const uint64_t now = time_us_64_p();
    if (last_tick_time_us_ == 0) last_tick_time_us_ = now;
    if (last_custom_update_time_us_ == 0) last_custom_update_time_us_ = now;
    if (last_input_poll_time_us_ == 0) last_input_poll_time_us_ = now;

    bool changed = false;

    // Same "elapsed >= threshold, or the clock wrapped" pattern as
    // David_And_John_program::update_step() - time_us_64_p() overflowing is
    // effectively never in practice, but costs nothing to guard against.

    // Input pass - the original's GameLoop(): every pass drains the pending
    // presses (GetPressedInputs()) and only hands them to the game when it
    // isn't input-blocked (IsInputBlocked()), so a press made during a
    // blocked window (startup jingle, animation) is simply dropped rather
    // than queued up for later.
    if (now - last_input_poll_time_us_ >= kInputPollUs || now < last_input_poll_time_us_) {
        last_input_poll_time_us_ = now;
        std::vector<std::string> inputs;
        inputs.swap(pending_inputs_);
        if (!program_->is_stopped() && !program_->is_input_blocked() && !inputs.empty()) {
            program_->handle_inputs(inputs);
            changed = true;
        }
    }

    // Base Update() (blink decay, animation frame advance, update_core()) -
    // 100ms, NOT the ~60Hz frame rate an earlier version used here, which
    // ran every animation and every update_core()-driven movement (e.g. the
    // hockey puck, projectiles) about 6x too fast.
    if (now - last_tick_time_us_ >= kTickUs || now < last_tick_time_us_) {
        last_tick_time_us_ = now;
        program_->tick();
        changed = true;
    }

    // PlayAnimation() in the original stops _customTimer for the whole
    // animation and restarts it afterwards, i.e. gameplay is frozen and the
    // next CustomUpdate() lands a full interval after the animation ends.
    // Rebasing the timestamp every pass while animating gives the same.
    if (program_->is_animating()) {
        last_custom_update_time_us_ = now;
    } else {
        const uint64_t custom_update_us = (uint64_t)(program_->custom_update_speed_ms()) * 1000ull;
        if (now - last_custom_update_time_us_ >= custom_update_us || now < last_custom_update_time_us_) {
            last_custom_update_time_us_ = now;
            program_->step_custom_update();
            changed = true;
        }
    }

    // Every increment_score() the game made this pass. Only counted while
    // in Endless mode (LCDonald's own Game_Scored handler does the same - the
    // running total is an Endless-only feature); otherwise just drained so
    // it can't pile up.
    // Burger's hidden "score-1" flash is a short real-time window, not tied to
    // any tick - refresh the snapshot when it starts and again when it ends.
    const bool hidden_group = program_->hidden_group_visible();
    if (hidden_group != hidden_group_shown_) {
        hidden_group_shown_ = hidden_group;
        changed = true;
    }

    const int scored = program_->take_score_events();
    if (endless_) endless_score_ += scored;

    if (changed) refresh_visible_cache();
}

bool LCDonald_fake_cpu::get_segments_state(uint8_t col, uint8_t line, uint8_t word) {
    for (size_t i = 0; i < segment_map_size_; i++) {
        const LCDonaldSegmentMapEntry& e = segment_map_[i];
        if (e.col == col && e.line == line && e.word == word) {
            return std::find(visible_cache_.begin(), visible_cache_.end(), e.name) != visible_cache_.end();
        }
    }
    return false;
}

void LCDonald_fake_cpu::set_input_pressed(const std::string& input_name, bool pressed) {
    auto it = std::find(buffered_inputs_.begin(), buffered_inputs_.end(), input_name);
    if (pressed) {
        if (it == buffered_inputs_.end()) {
            // Rising edge only - matches HandleInput()'s _bufferedKeyCodes
            // guard ("prevent holding the key down from spamming the input
            // buffer"). Already-latched inputs are silently ignored here
            // for every additional frame the button stays held.
            buffered_inputs_.push_back(input_name);
            pending_inputs_.push_back(input_name);
        }
    } else if (it != buffered_inputs_.end()) {
        buffered_inputs_.erase(it);
    }
}

void LCDonald_fake_cpu::start_game(bool endless) {
    if (!program_) return;
    program_->start(endless);
    endless_ = endless;
    endless_score_ = 0;
    program_->take_score_events();  // drop anything left over from a previous run
    buffered_inputs_.clear();
    pending_inputs_.clear();
    // Fresh timestamps so the first tick()/step_custom_update()/input pass
    // lands a full interval after this moment, same as a first-ever load.
    last_tick_time_us_ = 0;
    last_custom_update_time_us_ = 0;
    last_input_poll_time_us_ = 0;
    refresh_visible_cache();
}

namespace {
// "LCDS" + a version, so an incompatible future layout is rejected cleanly
// instead of being misread.
constexpr uint32_t kStateMagic = 0x5344434C;
constexpr uint32_t kStateVersion = 1;
}  // namespace

// The game itself (which LCDonald_program, and Burger or not) comes from the
// ROM/load_rom() on load, same as every other core - only the running state
// is stored. Real-time timers aren't: a restored game resumes with fresh
// tick/custom-update timestamps, as if just started.
bool LCDonald_fake_cpu::save_state(FILE* file) {
    if (!file || !program_) return false;
    LCDonaldStateIO io(file, true);
    uint32_t magic = kStateMagic, version = kStateVersion;
    uint64_t hdr = ((uint64_t)version << 32) | magic;
    io.io(hdr);
    io.io(endless_);
    io.io(endless_score_);
    return program_->serialize_state(io);
}

bool LCDonald_fake_cpu::load_state(FILE* file) {
    if (!file || !program_) return false;
    LCDonaldStateIO io(file, false);
    uint64_t hdr = 0;
    io.io(hdr);
    if (!io.ok() || (uint32_t)hdr != kStateMagic || (uint32_t)(hdr >> 32) != kStateVersion) return false;
    io.io(endless_);
    io.io(endless_score_);
    if (!program_->serialize_state(io)) {
        // Part of the state may already have been overwritten - start over
        // from a freshly constructed program (the just-loaded, not-yet-
        // started screen) rather than leave the game half-restored.
        select_game(game_id_);
        endless_ = false;
        endless_score_ = 0;
        refresh_visible_cache();
        return false;
    }
    buffered_inputs_.clear();
    pending_inputs_.clear();
    last_tick_time_us_ = 0;
    last_custom_update_time_us_ = 0;
    last_input_poll_time_us_ = 0;
    hidden_group_shown_ = false;
    refresh_visible_cache();
    return true;
}

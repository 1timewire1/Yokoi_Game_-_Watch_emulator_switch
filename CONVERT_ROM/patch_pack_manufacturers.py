"""One-off migration for the manufacturer rework (content_version 4 -> 5).

The old MANUFACTURER_EXPERIMENTAL bucket (id 5) was dissolved into real
per-manufacturer ones (see source/manufacturer_ids.py / GNW_LIST.md). The
pack's 70 games that used id 5 need their stored manufacturer_id rewritten,
Bassmate's display name changes to "Bassmate Computer (Telko)", and the
header's content_version becomes 5 so older/newer builds reject a pack of the
wrong generation.

Done as an in-place record patch rather than a full pack rebuild because a
few games in the live pack (the 8 injected from the old v3.3 pack, plus the
McDonald's/Burger Bard art) can't be regenerated by convert_switch.py alone -
this only touches the 100-byte game records (and appends Bassmate's new name
at the end of the file; the old string becomes dead bytes that the next run
of inject_pack_assets.py compacts away).

Usage:  python patch_pack_manufacturers.py <pack.ykp> [--out patched.ykp]
        (default: patch in place after copying the original to <pack>.pre_mfr)
"""
import argparse
import shutil
import struct
import sys
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent
sys.path.insert(0, str(SCRIPT_DIR))

import inject_pack_assets as ip  # noqa: E402  (parse_header / validate_pack_bytes)
from source.manufacturer_ids import (  # noqa: E402
    MANUFACTURER_ELEKTRONIKA, MANUFACTURER_KONAMI, MANUFACTURER_NELSONIC, MANUFACTURER_NINTENDO,
    MANUFACTURER_TIGER, MANUFACTURER_TRONICA, MANUFACTURER_VTECH,
)

# ref -> new manufacturer id, for the 70 games that used the old id 5.
TIGER_REFS = """TBATMAN TSPIDMAN TMKOMBAT TXMEN TSUPERMAN TBTOADS TKARNOV THOOK TBTTF TTRANSF2 TVINDICTR TJPARK
TSKELWARR TGARGNF TADDAMS TAPOLLO13 TBATFOR TBATMANA TDENNIS TDUMMIES TFLASH TGOLDEYE THALONE THALONE2
TINDAY TJDREDD TKAZAAM TMIGMAX TNMAREBC TOPALIENS TPITFIGHT TROBHOOD TROBOCOP2 TROCKTEER TROBOCOP3
TSF2010 TSHADOW TSJAM TSWAMPT TWWORLD TXMENPX""".split()
KONAMI_REFS = """KCONTRA KDRIBBLE KTOPGUN KGRADIUS KSKATEDIE KTMNT KBILLY KBOTTOM9 KCHQFLAG KLONERAN KNASCAR KTMNT2
KBUCKY KGARFLD KNFL KST25 KTMNT3 KTMNTBB KTOPGUN2 KBLADES""".split()
NEW_MFR = {r: MANUFACTURER_TIGER for r in TIGER_REFS}
NEW_MFR.update({r: MANUFACTURER_KONAMI for r in KONAMI_REFS})
NEW_MFR.update({
    "TRTREISL": MANUFACTURER_TRONICA,      # Treasure Island (Tronica)
    "VESARIF": MANUFACTURER_ELEKTRONIKA,   # Vesolaya arifmetika (Elektronika)
    "UCHITARI": MANUFACTURER_ELEKTRONIKA,  # Uchitel' arifmetiki (Elektronika)
    "NALTAIR": MANUFACTURER_ELEKTRONIKA,   # Altair (Nauchpribor)
    "BASSMATE": MANUFACTURER_NINTENDO,     # Bassmate Computer (Telko)
    "NSTARFOX": MANUFACTURER_NELSONIC, "NSMB3": MANUFACTURER_NELSONIC, "NSMW": MANUFACTURER_NELSONIC,
    "NUMMUNCH": MANUFACTURER_VTECH,        # Electronic Number Muncher (VTech)
})
assert len(NEW_MFR) == 70, len(NEW_MFR)
OLD_BASSMATE_NAME = "Bassmate Computer (Telko / Nintendo)"
NEW_BASSMATE_NAME = "Bassmate Computer (Telko)"

HEADER_SIZE = 36
GAME_ENTRY_SIZE = 100
OLD_EXPERIMENTAL_ID = 5


def norm(ref: str) -> str:
    return ref.replace("-", "_").upper()


def patch(buf: bytearray) -> dict:
    header = ip.parse_header(bytes(buf))
    if header["content_version"] >= 5:
        raise SystemExit(f"pack is already content_version {header['content_version']} - nothing to do")
    changed = {}
    for i in range(header["game_count"]):
        base = HEADER_SIZE + GAME_ENTRY_SIZE * i
        vals = list(struct.unpack_from("<25I", buf, base))
        ref = buf[vals[2]: vals[2] + vals[3]].decode("utf-8")
        if vals[24] != OLD_EXPERIMENTAL_ID:
            continue
        new_mfr = NEW_MFR[norm(ref)]  # KeyError = a game we didn't map: fail loudly
        vals[24] = new_mfr
        if norm(ref) == "BASSMATE":
            old_name = buf[vals[0]: vals[0] + vals[1]].decode("utf-8")
            assert old_name == OLD_BASSMATE_NAME, old_name
            new_bytes = NEW_BASSMATE_NAME.encode("utf-8")
            vals[0] = len(buf)          # absolute file offset of the appended string
            vals[1] = len(new_bytes)
            buf.extend(new_bytes)
        struct.pack_into("<25I", buf, base, *vals)
        changed[norm(ref)] = new_mfr
    # header.content_version is the 4th uint32 (magic, format, platform, content_version, ...)
    struct.pack_into("<I", buf, 12, 5)
    return changed


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("pack", type=Path)
    ap.add_argument("--out", type=Path, default=None)
    args = ap.parse_args()

    buf = bytearray(args.pack.read_bytes())
    changed = patch(buf)
    missing = set(NEW_MFR) - set(changed)
    if missing:
        raise SystemExit(f"expected these refs to carry the old experimental id but didn't: {sorted(missing)}")
    ip.validate_pack_bytes(bytes(buf))

    out = args.out
    if out is None:
        backup = args.pack.with_name(args.pack.name + ".pre_mfr")
        shutil.copyfile(args.pack, backup)
        print(f"Backed up original to: {backup}")
        out = args.pack
    out.write_bytes(bytes(buf))
    print(f"Patched {len(changed)} game records; content_version -> 5; wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
